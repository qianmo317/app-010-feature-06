// 每年使用对象存储，清晰易验证
// sf: 春节公历日期偏移（从当年1月1日起，0-indexed）
// md: 12个正常月的天数
// lm: 闰月月份（0=无闰月，1-12）
// ld: 闰月天数（0=无闰月）

export interface LunarYearData {
  sf: number;      // spring festival offset from Jan 1
  md: number[];    // 12 normal month days
  lm: number;      // leap month (0=none)
  ld: number;      // leap month days
}

function d(monthDays: number[], leapMonth: number, leapDays: number, springOffset: number): LunarYearData {
  return { md: monthDays, lm: leapMonth, ld: leapDays, sf: springOffset };
}

